/****************************************************************************
 * Included Files
 ****************************************************************************/

#include <nuttx/config.h>

#include <sys/mount.h>
#include <syslog.h>

#include <nuttx/fs/fs.h>
#include <nuttx/fdt.h>

#include "arm_internal.h"

/****************************************************************************
 * Pre-processor Definitions
 ****************************************************************************/

/* The QEMU virt-m machine writes the generated device tree into guest RAM
 * at this fixed base (VIRT_M_DTB_BASE in the QEMU machine); no external
 * .dtb file or -dtb argument is used.
 */

#define QEMU_M_DTB_BASE       0x20000000

/* NVIC external interrupts start at vector 16, so the guest IRQ number of a
 * device is its DTB "interrupts" line + 16.  This mirrors the A/R board's
 * QEMU_SPI_IRQ_BASE (32 for the GIC); the fdt_* hooks are reused unchanged.
 */

#define QEMU_M_IRQ_BASE       16

/****************************************************************************
 * Private Functions
 ****************************************************************************/

/****************************************************************************
 * Name: qemu_m_register_fdt_devices
 *
 * Description:
 *   Register the DTB generated by QEMU and run the architecture-independent
 *   FDT discovery hooks for the fixed peripherals (core0 only).  More hooks
 *   (virtio/PL061/ctucan/...) are added here as each device is brought up.
 *
 ****************************************************************************/

#if defined(CONFIG_LIBC_FDT) && defined(CONFIG_DEVICE_TREE)
static void qemu_m_register_fdt_devices(void)
{
  const void *fdt;

  fdt_register((const char *)QEMU_M_DTB_BASE);

  fdt = fdt_get();
  if (fdt == NULL)
    {
      syslog(LOG_ERR, "ERROR: no device tree at %p\n",
             (void *)QEMU_M_DTB_BASE);
      return;
    }

#ifdef CONFIG_WATCHDOG_CMSDK
  fdt_cmsdk_wdt_devices_register(fdt, QEMU_M_IRQ_BASE);
#endif
}
#endif

/****************************************************************************
 * Name: qemu_m_bringup
 *
 * Description:
 *   Bring up board features.  On core0 this registers the QEMU-generated
 *   DTB and the peripheral FDT hooks; it also mounts the basic pseudo file
 *   systems.
 *
 ****************************************************************************/

static int qemu_m_bringup(void)
{
  int ret = 0;

#if defined(CONFIG_LIBC_FDT) && defined(CONFIG_DEVICE_TREE)
  qemu_m_register_fdt_devices();
#endif

#ifdef CONFIG_FS_PROCFS
  ret = nx_mount(NULL, "/proc", "procfs", 0, NULL);
  if (ret < 0)
    {
      syslog(LOG_ERR, "ERROR: Failed to mount procfs at /proc: %d\n", ret);
    }
#endif

#ifdef CONFIG_FS_TMPFS
  ret = nx_mount(NULL, CONFIG_LIBC_TMPDIR, "tmpfs", 0, NULL);
  if (ret < 0)
    {
      syslog(LOG_ERR, "ERROR: Failed to mount tmpfs at %s: %d\n",
             CONFIG_LIBC_TMPDIR, ret);
    }
#endif

  return ret;
}

/****************************************************************************
 * Public Functions
 ****************************************************************************/

/****************************************************************************
 * Name: board_late_initialize
 ****************************************************************************/

#ifdef CONFIG_BOARD_LATE_INITIALIZE
void board_late_initialize(void)
{
  qemu_m_bringup();
}
#endif

/****************************************************************************
 * Name: board_app_initialize
 ****************************************************************************/

int board_app_initialize(uintptr_t arg)
{
  UNUSED(arg);
#ifndef CONFIG_BOARD_LATE_INITIALIZE
  return qemu_m_bringup();
#else
  return OK;
#endif
}
